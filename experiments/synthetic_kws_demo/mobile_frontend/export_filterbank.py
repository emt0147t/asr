"""
Exports the canonical Slaney Mel filterbank matrix (40 x 257) from torchaudio
to both a binary asset (mel_filterbank_40x257.bin) and a C/C++ header (mel_filterbank_40x257.h).
Governance Invariant: HUMAN DATA COLLECTION REMAINS STRICTLY BLOCKED.
"""

import sys
import hashlib
from pathlib import Path

if str(Path.cwd()) not in sys.path:
    sys.path.insert(0, str(Path.cwd()))

import numpy as np
import torchaudio.transforms as T


def sha256_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest().upper()


def export_mel_filterbank():
    print("=" * 72)
    print("Exporting Canonical Slaney Mel Filterbank Matrix (40 x 257)...")
    print("=" * 72)

    mel = T.MelSpectrogram(
        sample_rate=16000,
        n_fft=512,
        win_length=400,
        hop_length=160,
        n_mels=40,
        norm="slaney",
        mel_scale="slaney",
        f_min=20.0,
        f_max=8000.0
    )
    # torchaudio stores fb as (n_freqs=257, n_mels=40)
    fb_matrix = mel.mel_scale.fb.numpy().T.astype(np.float32)  # shape: (40, 257)

    assert fb_matrix.shape == (40, 257), f"Expected shape (40, 257), got {fb_matrix.shape}"
    assert fb_matrix.dtype == np.float32, f"Expected float32, got {fb_matrix.dtype}"

    base_dir = Path("experiments/synthetic_kws_demo/mobile_frontend")
    bin_path = base_dir / "assets" / "mel_filterbank_40x257.bin"
    hdr_path = base_dir / "include" / "mel_filterbank_40x257.h"

    # 1. Export raw binary float32 (little-endian)
    bin_path.parent.mkdir(parents=True, exist_ok=True)
    bin_path.write_bytes(fb_matrix.tobytes())
    bin_sha = sha256_file(bin_path)

    # 2. Export C/C++ header with static table
    hdr_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Autogenerated canonical Slaney Mel Filterbank Matrix (40 x 257) */",
        "/* Extracted from torchaudio.transforms.MelSpectrogram (Slaney scale & norm) */",
        "/* Dtype: float32, Little-Endian, Size: 40 x 257 = 10,280 floats */",
        "#ifndef KWS_MEL_FILTERBANK_40X257_H",
        "#define KWS_MEL_FILTERBANK_40X257_H",
        "",
        "#define KWS_MEL_BANDS 40",
        "#define KWS_FFT_BINS 257",
        "",
        "static const float KWS_MEL_FILTERBANK[40][257] = {"
    ]

    for m in range(40):
        row = fb_matrix[m]
        vals = ", ".join(f"{v:.9e}f" for v in row)
        comma = "," if m < 39 else ""
        lines.append(f"    /* Mel band {m:02d} */")
        lines.append(f"    {{{vals}}}{comma}")

    lines.append("};")
    lines.append("")
    lines.append("#endif /* KWS_MEL_FILTERBANK_40X257_H */")
    lines.append("")

    hdr_path.write_text("\n".join(lines), encoding="utf-8")
    hdr_sha = sha256_file(hdr_path)

    print(f"  Binary Asset:  {bin_path}")
    print(f"  Binary SHA256: {bin_sha}")
    print(f"  Header Asset:  {hdr_path}")
    print(f"  Header SHA256: {hdr_sha}")
    print(f"  Dimensions:    40 x 257 (10,280 float32 elements = 41,120 bytes)")
    print(f"  Non-zero bins: {np.count_nonzero(fb_matrix)} / 10280")
    print(f"  Min non-zero:  {np.min(fb_matrix[fb_matrix > 0]):.9e}")
    print(f"  Max value:     {np.max(fb_matrix):.9e}")

    return {
        "binary_path": str(bin_path),
        "binary_sha256": bin_sha,
        "header_path": str(hdr_path),
        "header_sha256": hdr_sha,
        "shape": [40, 257],
        "dtype": "float32",
        "size_bytes": bin_path.stat().st_size
    }


if __name__ == "__main__":
    export_mel_filterbank()
